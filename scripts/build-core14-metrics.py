#!/usr/bin/env python3
"""Build src/core14_metrics.rs: the Adobe Core 14 AFM advance widths of
the ten Latin Standard 14 fonts (Times, Helvetica and Courier families),
by glyph name.

The widths are Adobe's Core 14 AFM metrics as transcribed in the pdf.js
sources (`src/core/metrics.js`, Apache-2.0) — the same source as the
Symbol and ZapfDingbats widths in src/symbol_fonts.rs. The file read is
checked against METRICS_SHA256 so a rebuild is reproducible.

    scripts/build-core14-metrics.py            # regenerate src/core14_metrics.rs
    scripts/build-core14-metrics.py --check    # verify the committed file is current
"""
import hashlib, os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = "https://raw.githubusercontent.com/mozilla/pdf.js/master/src/core/metrics.js"
METRICS_SHA256 = "7958e89725c43a152222d5cb6b3b6fcaa6d7995bd9bd6fe18e26d726f56a2a0c"
OUT = os.path.join(ROOT, "src", "core14_metrics.rs")
FONTS = [
    "Helvetica", "Helvetica-Bold", "Helvetica-BoldOblique", "Helvetica-Oblique",
    "Times-Roman", "Times-Bold", "Times-BoldItalic", "Times-Italic",
]


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "kasane-pdf build-core14-metrics"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def table(src, font):
    key = f't.{font} = getLookupTableFactory' if "-" not in font else f't["{font}"] = getLookupTableFactory'
    i = src.index(key)
    j = src.index("});", i)
    body = src[i:j]
    out = {}
    for m in re.finditer(r'''t(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\]) = (\d+);''', body):
        out[m.group(1) or m.group(2)] = int(m.group(3))
    return out


def render(src):
    lines = [
        "//! The Adobe Core 14 AFM advance widths of the Latin Standard 14",
        "//! fonts, by glyph name (Courier: 600 for every glyph). A",
        "//! non-embedded Standard 14 font without `/Widths` is laid out with",
        "//! these, as readers lay it out (ISO 32000-1 §9.6.2.2).",
        "//!",
        "//! Source: Adobe's Core 14 AFM metrics as transcribed in the pdf.js",
        "//! project's `src/core/metrics.js` (Apache-2.0; the AFM files'",
        "//! ReadMe permits use and redistribution with or without",
        "//! modification). Generated by `scripts/build-core14-metrics.py`; do",
        "//! not edit by hand.",
        "",
    ]
    for font in FONTS:
        t = table(src, font)
        ident = font.upper().replace("-", "_")
        lines.append(f"/// {font}: (glyph name, width), sorted by name.")
        lines.append(f"pub(crate) static {ident}: &[(&str, u16)] = &[")
        for name in sorted(t):
            lines.append(f'    ("{name}", {t[name]}),')
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main():
    src = fetch(URL)
    digest = hashlib.sha256(src).hexdigest()
    if METRICS_SHA256 and digest != METRICS_SHA256:
        sys.exit(f"metrics.js changed upstream ({digest}); review and update METRICS_SHA256")
    out = render(src.decode())
    if "--check" in sys.argv:
        ok = open(OUT).read() == out
        print("ok" if ok else "src/core14_metrics.rs is out of date")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(out)
    print("wrote", OUT, "from metrics.js", digest)


if __name__ == "__main__":
    main()
