#!/usr/bin/env python3
"""Generate src/agl.rs from the Adobe Glyph List (glyphlist.txt, AGL 2.0,
https://github.com/adobe-type-tools/agl-aglfn, BSD-3-Clause).

    python3 scripts/gen-agl.py path/to/glyphlist.txt > src/agl.rs

Entries mapping into the Private Use Area (corporate-use code points)
are left out: they carry no meaning as text.
"""
import hashlib
import sys

path = sys.argv[1]
raw = open(path, "rb").read()
notice = []
rows = []
for line in raw.decode("utf-8").splitlines():
    if line.startswith("#"):
        if not rows and line.startswith("# ") and "Format" not in line:
            notice.append(line[2:].rstrip())
        continue
    if not line.strip():
        continue
    name, cps = line.split(";")
    vals = [int(c, 16) for c in cps.split()]
    if any(0xE000 <= v <= 0xF8FF for v in vals):
        continue
    rows.append((name, "".join(chr(v) for v in vals)))
rows.sort(key=lambda r: r[0].encode())
# The licence block: the header up to the end of the disclaimer.
lic = []
for l in notice:
    lic.append(l)
    if l.startswith("SOFTWARE, EVEN IF ADVISED"):
        break
out = sys.stdout
out.write("// @generated by scripts/gen-agl.py — do not edit.\n")
out.write(f"// Source: glyphlist.txt (Adobe Glyph List 2.0), sha256 {hashlib.sha256(raw).hexdigest()}.\n")
out.write("// Entries mapping into the Private Use Area are omitted.\n//\n")
for l in lic:
    out.write(("// " + l).rstrip() + "\n")
out.write("\n/// Adobe Glyph List: glyph name → Unicode string, sorted by name.\n")
out.write("pub(crate) static AGL: &[(&str, &str)] = &[\n")
for n, s in rows:
    esc = "".join(f"\\u{{{ord(c):04X}}}" for c in s)
    out.write(f'    ("{n}", "{esc}"),\n')
out.write("];\n")
