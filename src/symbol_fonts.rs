/// Unicode for a glyph name of the Symbol or ZapfDingbats repertoire
/// that the Adobe Glyph List does not carry (or carries only as a
/// private-use value).
pub(crate) fn name_to_unicode(name: &str) -> Option<u32> {
    DINGBATS_NAME_UNICODE
        .iter()
        .chain(SYMBOL_NAME_UNICODE.iter())
        .find(|(n, _)| *n == name)
        .map(|(_, u)| *u)
}

/// AFM advance (1/1000 em) of a glyph name in `table`.
pub(crate) fn afm_width(table: &[(&str, u16)], name: &str) -> Option<f64> {
    table
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, w)| *w as f64)
}
